#!/usr/bin/env python3
"""Executable gate for the am-halftone skill.

Verifies: ImageMagick is installed, bin/halftone.sh runs, and the three
grid modes produce valid images with the color counts the method promises:

  truecmyk     -> binary per channel, so at most 2^4 = 16 unique colors
  pink-old     -> gray -> 2 colors -> black/pink, so exactly 2 unique colors
  pink-palette -> -remap + -colors 32, so at most 32 unique colors

The test image is generated by ImageMagick itself (plasma + shapes), per the
blog author's request that their photos not be fed to LLMs. Exits non-zero
on any failure.
"""
import os
import shutil
import subprocess
import sys
import tempfile

SKILL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HALFTONE = os.path.join(SKILL_DIR, "bin", "halftone.sh")

failures = []


def fail(msg):
    failures.append(msg)
    print(f"FAIL: {msg}", file=sys.stderr)


def run(*args):
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode != 0:
        fail(f"{' '.join(args[:3])}... exited {r.returncode}: {r.stderr.strip()[-300:]}")
    return r


def unique_colors(im, path):
    r = run(im, path, "-format", "%k", "info:")
    try:
        return int(r.stdout.strip())
    except ValueError:
        fail(f"could not read unique color count of {path}: {r.stdout!r}")
        return -1


def main():
    if not os.access(HALFTONE, os.X_OK):
        fail(f"{HALFTONE} is not executable")

    im = (shutil.which("magick") or shutil.which("convert")
          or os.path.expanduser("~/workspace/imagemagick/bin/magick"))
    if not im or not (shutil.which(os.path.basename(im)) or os.access(im, os.X_OK)):
        fail("no ImageMagick found (need magick/convert on PATH or ~/workspace/imagemagick)")
        print("RESULT: FAIL", file=sys.stderr)
        return 1
    print(f"ImageMagick: {im}")

    tmp = tempfile.mkdtemp(prefix="am-halftone-check-")
    test = os.path.join(tmp, "test.png")
    # Self-made test image: colorful plasma, darkened shapes for tonal range.
    run(im, "-size", "400x300", "plasma:fractal", "-modulate", "100,70",
        "-fill", "black", "-draw", "circle 100,80 100,180",
        "-fill", "white", "-draw", "rectangle 250,150 380,260", test)
    if not os.path.exists(test):
        fail("test image was not generated")
        print("RESULT: FAIL", file=sys.stderr)
        return 1

    cases = [
        ("truecmyk", 16, lambda n: n <= 16, f"<=16 colors"),
        ("pink-old", 2, lambda n: n == 2, "exactly 2 colors"),
        ("pink-palette", 32, lambda n: n <= 32, "<=32 colors"),
        ("rgb", 8, lambda n: n <= 8, "<=8 colors"),
    ]
    for mode, _bound, ok, desc in cases:
        out = os.path.join(tmp, f"out-{mode}.png")
        run("bash", HALFTONE, "--in", test, "--out", out,
            "--mode", mode, "--width", "400", "--scale", "1")
        if not os.path.exists(out):
            fail(f"{mode}: no output file")
            continue
        n = unique_colors(im, out)
        w = run(im, out, "-format", "%w", "info:").stdout.strip()
        print(f"{mode}: {n} unique colors (expect {desc}), width {w}")
        if n >= 0 and not ok(n):
            fail(f"{mode}: {n} unique colors, expected {desc}")
        if w != "400":
            fail(f"{mode}: width {w}, expected 400")

    shutil.rmtree(tmp, ignore_errors=True)
    if failures:
        print(f"RESULT: FAIL ({len(failures)} failures)", file=sys.stderr)
        return 1
    print("RESULT: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
